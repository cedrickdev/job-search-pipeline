export function useLocale() {
  const locale = useCookie<AppLocale>('app_locale', { default: () => 'en', maxAge: 60 * 60 * 24 * 365 })
  const current = computed<AppLocale>({
    get: () => locale.value === 'fr' ? 'fr' : 'en',
    set: (value) => { locale.value = value },
  })

  function setLocale(value: AppLocale) {
    current.value = value
  }

  // Keep document language metadata in sync for screen readers, spellcheck,
  // translation tools and browser language heuristics.
  if (import.meta.client) {
    watch(current, (value) => {
      document.documentElement.lang = value
    }, { immediate: true })
  }

  function t(key: string, fallback?: string): string {
    const value = messages[current.value][key] ?? messages.en[key]
    if (typeof value === 'function') return value(key)
    return value ?? fallback ?? key
  }

  function localize(english: string, french: string): string {
    return current.value === 'fr' ? french : english
  }

  return { locale: current, setLocale, t, localize }
}
